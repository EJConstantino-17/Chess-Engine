static unsigned char reductions[256][256];
static int initialized;
void lmr_init(void) {
    if (initialized) return;
    for (int d = 4; d < 256; ++d)
        for (int m = 4; m < 256; ++m)
            reductions[d][m] = (unsigned char)(1 + (unsigned)logs[d] * logs[m] / (3U * 1024U * 1024U));
    initialized = 1;
}
int lmr_reduction(int depth, int legal_move_index) {
    lmr_init();
    if (depth < 4 || legal_move_index < 4) return 0;
    if (depth > 255) depth = 255;
    if (legal_move_index > 255) legal_move_index = 255;
    return reductions[depth][legal_move_index];
}
